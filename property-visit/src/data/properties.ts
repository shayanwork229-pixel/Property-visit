export function findProperty(slug: string) {
  return PROPERTIES.find((p) => p.slug === slug);
}

export function findPropertyById(id: string) {
  return PROPERTIES.find((p) => p.id === id);
}

export function similarProperties(property: Property, limit = 3) {
  return PROPERTIES.filter((p) => p.id !== property.id)
    .map((p) => ({
      p,
      score:
        (p.type === property.type ? 3 : 0) +
        (p.citySlug === property.citySlug ? 2 : 0) +
        (p.purpose === property.purpose ? 1 : 0),
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.p);
}
